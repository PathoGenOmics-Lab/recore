#!/usr/bin/env python3
"""Turn the exported wordmark into the two assets the project actually ships.

The export arrives from the drawing program with editor metadata, a fixed pixel
size, `preserveAspectRatio="none"` (which lets any CSS box stretch it out of
shape) and a canvas much larger than the artwork, so the mark drew at a fraction
of whatever box it was given.

It also carries one palette, drawn for paper. Three of its six inks land between
1.8:1 and 2.3:1 against GitHub's dark canvas, under the 3:1 WCAG asks of a
non-text graphic, so a dark page needs its own file rather than a filter.

    python3 tools/make_logo_variants.py

Reads  assets/recore_logo_source.svg
Writes assets/recore_logo.svg       cleaned and cropped, for light backgrounds
       assets/recore_logo_dark.svg  the same mark lifted for dark backgrounds
"""

from __future__ import annotations

import colorsys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "recore_logo_source.svg"
LIGHT = ROOT / "assets" / "recore_logo.svg"
DARK = ROOT / "assets" / "recore_logo_dark.svg"
# The HTML report inlines the light mark and recolours it in CSS rather than
# carrying a second copy of a 30 KB asset. These markers bracket the generated
# rules so regenerating cannot drift from the dark file.
REPORT_CSS = ROOT / "src" / "pipeline" / "report_assets" / "report.css"
# The website only serves what lives under docs/, so the two variants are
# copied there rather than kept in a second place by hand.
DOCS_ASSETS = ROOT / "docs" / "assets"
CSS_BEGIN = "/* >>> generated by tools/make_logo_variants.py */"
CSS_END = "/* <<< generated */"

# Bounding box of the artwork inside the export's 2048x1153 canvas, plus a few
# units so antialiased edges are not clipped.
CONTENT_VIEWBOX = "98 120 1857 854"

# The canvas the dark variant has to survive. GitHub's dark is #0d1117 and the
# documentation slate is within a tenth of a contrast point of it.
DARK_CANVAS = "#0d1117"
# Comfortably above the 3:1 that WCAG 1.4.11 asks of a non-text graphic.
CONTRAST_FLOOR = 4.5


def _channel(c: float) -> float:
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def luminance(rgb: tuple[float, float, float]) -> float:
    r, g, b = (_channel(x) for x in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: tuple[float, ...], b: tuple[float, ...]) -> float:
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def parse_colour(text: str) -> tuple[float, float, float]:
    text = text.strip()
    if text.startswith("#"):
        h = text[1:]
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    m = re.match(r"rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)", text)
    if not m:
        raise ValueError(f"cannot parse colour {text!r}")
    return tuple(int(m.group(i)) / 255 for i in (1, 2, 3))


def to_hex(rgb: tuple[float, float, float]) -> str:
    return "#%02x%02x%02x" % tuple(round(max(0.0, min(1.0, c)) * 255) for c in rgb)


def lift(rgb: tuple[float, float, float]) -> tuple[float, float, float]:
    """Raise lightness, hue and saturation fixed, until the ink clears the floor.

    Hue is what makes the mark recognisable, so it is the one thing that does not
    move: an ink that already clears the floor is returned untouched.
    """
    canvas = parse_colour(DARK_CANVAS)
    if contrast(rgb, canvas) >= CONTRAST_FLOOR:
        return rgb
    h, l, s = colorsys.rgb_to_hls(*rgb)
    low, high = l, 1.0
    for _ in range(40):
        mid = (low + high) / 2
        if contrast(colorsys.hls_to_rgb(h, mid, s), canvas) >= CONTRAST_FLOOR:
            high = mid
        else:
            low = mid
    return colorsys.hls_to_rgb(h, high, s)


def clean(svg: str) -> str:
    """Strip the editor's leavings and make the root scale from its viewBox."""
    svg = re.sub(r"<\?xml[^>]*\?>\s*", "", svg)
    svg = re.sub(r"<sodipodi:namedview\b.*?(?:/>|</sodipodi:namedview>)", "", svg, flags=re.S)
    svg = re.sub(r"<metadata\b.*?</metadata>", "", svg, flags=re.S)
    svg = re.sub(r'\s+(?:inkscape|sodipodi):[\w-]+="[^"]*"', "", svg)
    svg = re.sub(r'\s+xmlns:(?:inkscape|sodipodi|svg)="[^"]*"', "", svg)
    # Editor ids on every path are dead weight; the gradient ids are referenced.
    referenced = set(re.findall(r"url\(#([^)]+)\)", svg))
    svg = re.sub(
        r'\s+id="([^"]+)"',
        lambda m: m.group(0) if m.group(1) in referenced else "",
        svg,
    )
    svg = re.sub(r'\s+transform="translate\(0,0\)"', "", svg)

    root = re.match(r"<svg[^>]*>", svg, re.S)
    head = root.group(0)
    new_head = head
    for attr in ("width", "height", "preserveAspectRatio", "style"):
        new_head = re.sub(r'\s+%s="[^"]*"' % attr, "", new_head)
    new_head = re.sub(r'viewBox="[^"]*"', f'viewBox="{CONTENT_VIEWBOX}"', new_head)
    if "role=" not in new_head:
        new_head = new_head.replace("<svg", '<svg role="img" aria-label="Recore"', 1)
    svg = new_head + svg[root.end():]
    return re.sub(r"\n{3,}", "\n\n", svg).strip() + "\n"


def darken(svg: str) -> tuple[str, dict[str, str]]:
    mapping: dict[str, str] = {}

    def swap(match: re.Match[str]) -> str:
        prop, value = match.group(1), match.group(2)
        if value.startswith("url(") or value in {"none", "currentColor"}:
            return match.group(0)
        out = to_hex(lift(parse_colour(value)))
        mapping[value] = out
        return f'{prop}="{out}"'

    return re.sub(r'(fill|stop-color|stroke)="([^"]+)"', swap, svg), mapping


def css_overrides(mapping: dict[str, str]) -> str:
    """Dark-theme fill overrides for the inlined mark, one rule per ink."""
    rules = [
        CSS_BEGIN,
        "/* The report inlines the light mark, so dark mode repaints its inks to",
        "   the values in assets/recore_logo_dark.svg. Do not edit by hand: run",
        "   python3 tools/make_logo_variants.py */",
    ]
    for before, after in sorted(mapping.items()):
        if before == after:
            continue
        for prop in ("fill", "stop-color"):
            rules.append(
                f':root[data-theme="dark"] .topbar-logo svg [{prop}="{before}"] '
                f"{{ {prop}: {after}; }}"
            )
    rules.append(CSS_END)
    return "\n".join(rules)


def write_report_css(mapping: dict[str, str]) -> int:
    css = REPORT_CSS.read_text()
    block = css_overrides(mapping)
    start, end = css.find(CSS_BEGIN), css.find(CSS_END)
    if start < 0 or end < 0:
        raise SystemExit(
            f"markers {CSS_BEGIN} / {CSS_END} not found in {REPORT_CSS}"
        )
    REPORT_CSS.write_text(css[:start] + block + css[end + len(CSS_END):])
    return block.count("\n") - 4


def main() -> int:
    source = SOURCE.read_text()
    light = clean(source)
    LIGHT.write_text(light)

    dark, mapping = darken(light)
    dark = dark.replace(
        '<svg role="img" aria-label="Recore"',
        '<svg role="img" aria-label="Recore"',
        1,
    )
    DARK.write_text(dark)

    rules = write_report_css(mapping)
    for asset in (LIGHT, DARK):
        (DOCS_ASSETS / asset.name).write_text(asset.read_text())

    canvas = parse_colour(DARK_CANVAS)
    print(f"{REPORT_CSS.relative_to(ROOT)}  {rules:>6} generated rules")
    print(f"{LIGHT.relative_to(ROOT)}  {len(light):>6} bytes")
    print(f"{DARK.relative_to(ROOT)}  {len(dark):>6} bytes")
    print(f"{DOCS_ASSETS.relative_to(ROOT)}/  {'':>6} both copied for the website")
    print()
    print(f"{'ink':>16}  {'lifted to':>9}  {'was':>5}  {'now':>5}")
    for before, after in sorted(mapping.items()):
        print(
            f"{before:>16}  {after:>9}  "
            f"{contrast(parse_colour(before), canvas):5.2f}  "
            f"{contrast(parse_colour(after), canvas):5.2f}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
